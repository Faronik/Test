import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createHash,randomBytes,pbkdf2Sync} from 'node:crypto';
const [binary,config,folder]=process.argv.slice(2);
assert(binary&&config&&folder,'Usage: node native-import.mjs BINARY CONFIG EMPTY_FIXTURE_FOLDER');
mkdirSync(join(folder,'photos'),{recursive:true});
const file=join(folder,'склад.sqlite3'),sqlite=new DatabaseSync(file),time=new Date().toISOString();
sqlite.exec('PRAGMA journal_mode=WAL; PRAGMA wal_autocheckpoint=0');
sqlite.exec(readFileSync(new URL('./legacy-schema.sql',import.meta.url),'utf8'));
const salt=randomBytes(16),password='native-import-test-password';
const hash='pbkdf2_sha256$310000$'+salt.toString('hex')+'$'+pbkdf2Sync(password,salt,310000,32,'sha256').toString('hex');
sqlite.prepare("INSERT INTO role_definitions VALUES('ADMIN','Администратор','[]',1)").run();
sqlite.prepare("INSERT INTO users(id,username,password_hash,role,created_at) VALUES(1,'legacy-native',?,'ADMIN',?)").run(hash,time);
const photo=randomBytes(16).toString('hex')+'.png',image=readFileSync(new URL('../web/logo.png',import.meta.url));
